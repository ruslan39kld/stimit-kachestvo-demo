export type VerdictLevel = 'хорошо' | 'средне' | 'плохо';

export type AgentStageId =
  | 'analyst'
  | 'evaluator'
  | 'critic'
  | 'calibrator'
  | 'finalizer';

export interface ReplyOption {
  id: string;
  text: string;
  isMain: boolean;
  altOperatorReply?: string;
}

export interface AnalystSnapshot {
  problem: string;
  request: string;
  status: string;
}

export interface ScenarioStep {
  stepNumber: number;
  options: ReplyOption[];
  mainOperatorReply: string;
  analyst: AnalystSnapshot;
  evaluatorObservation: string | null;
}

export interface CriterionEvaluation {
  criterion: string;
  rating: VerdictLevel;
  reason: string;
}

export interface FinalAnalysis {
  score: number;
  verdict: VerdictLevel;
  verdictLabel: string;
  evaluator: CriterionEvaluation[];
  critic: string[];
  calibrator: string;
  finalizer: {
    summaryTitle: string;
    why: string[];
    whatWasGood: string[];
    whatToImprove: string[];
  };
}

export interface Scenario {
  id: string;
  number: number;
  title: string;
  shortDescription: string;
  orderNumber: string;
  stepsCount: number;
  isFeatured: boolean;
  steps: ScenarioStep[];
  finalAnalysis: FinalAnalysis;
}

